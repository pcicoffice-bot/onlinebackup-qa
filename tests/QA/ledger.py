def step_result(folder, jid, pattern):
    import fnmatch
    j = journey_steps(folder, jid)
    hits = [s for s in (j.get('steps') or []) if fnmatch.fnmatchcase(s.get('step', ''), pattern) and s.get('result') in ('PASS', 'FAIL')]
    if not hits: return None
    return 'FAIL' if any(s['result'] == 'FAIL' for s in hits) else 'PASS', hits[-1]

def chains(wruns):
    L = ['# END-TO-END CHAINS — generated by `tests/QA/ledger.py` (do not edit by hand)', '',
         'Each step names the journey and step whose real result proves it. **FULL CHAIN VERIFIED** only when every step '
         'passed in ONE continuous run on ONE Windows machine (the VM: the same disk before and after its real restarts). '
         'Ten separate passes on different machines or runs are listed, but they never make a chain verified.', '']
    # group the phases by run: a VM run = runs/<id>/vm/out/vm-*; the hosted Windows job = runs/<id>
    groups = {}
    for folder, facts, js in wruns:
        rel = os.path.relpath(folder, os.path.join(here, 'reports', 'windows')).replace(os.sep, '/')
        parts = rel.split('/')
        key = (parts[0], 'vm' if 'vm' in parts else 'hosted')
        groups.setdefault(key, []).append((folder, facts, {j['id']: j for j in js}))
    for cid, title, steps in CHAINS:
        L.append('## %s %s' % (cid, title)); L.append('')
        if not groups: L.append('No Windows run in reports/windows: every step NOT TESTED.'); L.append('')
        for (run, kind), phases in sorted(groups.items()):
            machine = '; '.join(sorted(set(str(f.get('windows', '?')) for _, f, _ in phases)))
            L.append('### run %s — %s (%s)' % (run, 'virtual machine, real restarts' if kind == 'vm' else 'hosted Windows runner, no restart possible', machine))
            L.append(''); L.append('| # | Step | Journey | Result | Evidence |'); L.append('|---|---|---|---|---|')
            allpass = True
            # ONE machine: every phase of the run on the same computer (a VM that was replaced or reinstalled half-way
            # is not one continuous run)
            computers = set(str(f.get('computer', '?')) for _, f, _ in phases)
            if len(computers) != 1 or '?' in computers or 'None' in computers:
                allpass = False
            for i, (name, jid, pat) in enumerate(steps, 1):
                found = []
                for folder, facts, js in phases:
                    if jid in js:
                        r = step_result(folder, jid, pat)
                        if r: found.append((r, folder))
                if not found:
                    allpass = False; L.append('| %d | %s | %s | NOT TESTED | — |' % (i, name, jid)); continue
                # a step that ran in several phases (W19 after each restart) passes only if it passed in EVERY one: the
                # last phase alone (a later PASS) once hid an earlier FAIL
                bad = [f for f in found if f[0][0] != 'PASS']
                (res, s), folder = bad[0] if bad else found[-1]
                if res != 'PASS': allpass = False
                ev = rel_evidence(os.path.join(folder, jid)) + ((' · ' + s['screenshot']) if str(s.get('screenshot', '')).endswith('.png') else '')
                L.append('| %d | %s | %s | %s | %s — %s |' % (i, name, jid, res, ev, str(s.get('actual', ''))[:160].replace('|', '/').replace('\n', ' ')))
            verdict = 'FULL CHAIN VERIFIED' if (allpass and (kind == 'vm' or cid != 'C1')) else 'NOT VERIFIED'
            if cid == 'C1' and kind != 'vm' and allpass: verdict = 'NOT VERIFIED (no real restart on a hosted runner)'
            L.append('')
            if len(computers) != 1: L.append('The phases of this run name %d computers (%s): not one continuous run on one machine.' % (len(computers), ', '.join(sorted(computers)))); L.append('')
            L.append('**%s %s, run %s: %s**' % (cid, title, run, verdict)); L.append('')
    open(os.path.join(here, 'END-TO-END-CHAINS.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')

if __name__ == '__main__':
    res = C.results(); rows = C.evaluate(res); wr = windows_runs(); K = C.xunit_kinds()
    ledger(rows, res, bug_commits(), wr); chains(wr)
    print('MASTER-QA-LEDGER.md and END-TO-END-CHAINS.md written;', len(wr), 'Windows phase(s) read')
