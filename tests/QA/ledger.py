#!/usr/bin/env python3
"""
The QA source of truth, generated — never typed by hand:
  python3 tests/QA/ledger.py      ->  tests/QA/MASTER-QA-LEDGER.md and tests/QA/END-TO-END-CHAINS.md
Inputs (the last real runs only): capabilities.py (every capability, its tests by layer and dimension; xUnit trx,
Playwright last-run.json, Windows windows-*.json under reports/windows), docs/R1-BUGLOG.md (bugs and the commit that
recorded each fix), the Windows evidence (journeys, steps, visual / UX findings).
A capability is PASS only when all three layers are verified by tests that ran and passed; a chain is FULL CHAIN
VERIFIED only when every step passed in ONE continuous run on one Windows machine (the VM: before and after its real
restarts). An agent's word is never evidence: only these files are.
"""
