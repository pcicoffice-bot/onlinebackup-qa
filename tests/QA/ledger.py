def git(*a):
    try: return subprocess.run(['git', '-C', repo] + list(a), capture_output=True, text=True, timeout=60).stdout.strip()
    except Exception: return ''

def bug_commits():
    """the commit that added each bug's row to the bug log (rows are written with their fix)"""
    out = {}
    for n in BUGS:
        h = git('log', '--format=%h', '-S', '| %d | ' % n, '--', 'docs/R1-BUGLOG.md').split('\n')
        out[n] = h[-1] if h and h[-1] else '?'
    return out

def windows_runs():
    """every Windows phase summary under reports/windows: (folder, facts, journeys); a run id per folder"""
    base = os.path.join(here, 'reports', 'windows'); runs = []
    for f in sorted(glob.glob(os.path.join(base, '**', 'windows-*.json'), recursive=True)):
        if not re.match(r'^windows-(main|before-reboot|after-reboot)\.json$', os.path.basename(f)): continue   # not windows-state.json
        try: d = json.load(open(f, encoding='utf-8-sig'))
        except Exception: continue
        runs.append((os.path.dirname(f), d.get('facts', {}), d.get('journeys') or []))
    return runs

def journey_steps(folder, jid):
    try: return json.load(open(os.path.join(folder, jid, 'journey.json'), encoding='utf-8-sig')) or {}
    except Exception: return {}

def rel_evidence(folder):
    r = os.path.relpath(folder, os.path.join(here, 'reports', 'windows')).replace(os.sep, '/')
    return EVIDENCE_URL + r

def ledger(rows, res, commits, wruns):
    global K
    bugs_by_cap = {}
    for n, caps in BUGS.items():
        for c in caps: bugs_by_cap.setdefault(c, []).append(n)
    # visual / UX status per capability from the Windows journeys that prove it
    jv = {}
    for folder, facts, js in wruns:
        for j in js: jv.setdefault(j['id'], []).append((j.get('visual'), j.get('ux'), folder))
    L = ['# MASTER QA LEDGER — generated by `tests/QA/ledger.py` from the last real runs (do not edit by hand)', '',
         'Status: **PASS** = verified in all three layers (component, integration, end-to-end) by tests that ran and passed; '
         '**PARTIAL** = some layer missing (listed); **NOT TESTED** = no layer verified; **FAIL** = a test of it fails now. '
         'Windows tests count only when the journey really ran on Windows and passed. Evidence = the test ids below, whose '
         'results come from `tests/QA/reports/trx/xunit.trx`, `tests/QA/reports/last-run.json` and the Windows runs in the branch `qa-evidence`.', '']
    crit = [r for r in rows if r['critical']]
    def n(st): return sum(1 for r in crit if r['status'] == st)
    L.append('Critical capabilities: %d — PASS %d, PARTIAL %d, NOT TESTED %d, FAIL %d.' % (len(crit), n('FULL'), n('PARTIAL'), n('NONE'), n('FAILING')))
    L.append('')
    L.append('| ID | Capability | Crit. | Status | Component | Integration | E2E | Windows | Failure | Recovery | Visual/UX | Bugs (fix commit) | Missing |')
    L.append('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    st = {'FULL': 'PASS', 'PARTIAL': 'PARTIAL', 'NONE': 'NOT TESTED', 'FAILING': 'FAIL'}
    for r in rows:
        lay = r['layers']
        def lv(Ly): return '%s (%d)' % (lay[Ly]['status'], len(lay[Ly].get('tests', [])) if isinstance(lay[Ly].get('tests'), list) else 0)
        dims = r['dims']
        win = sorted(set(t for d in dims.values() if not isinstance(d, C.NA) for t in d if t.startswith('win:')))
        winst = ', '.join('%s %s' % (t[4:], {'Passed': 'PASS', 'Failed': 'FAIL'}.get(res.get(t), 'NOT RUN')) for t in win) or '—'
        def dim(k):
            d = dims.get(k)
            if isinstance(d, C.NA): return 'N/A'
            ok = [t for t in d if res.get(t) == 'Passed' or C.resolve(t, res) == 'Passed']
            return '%d/%d' % (len(ok), len(d)) if d else '0'
        vu = []
        for t in win:
            for v, u, f in jv.get(t[4:], []): vu.append('%s: V %s, UX %s' % (t[4:], v, u))
        bl = ', '.join('%d (%s)' % (b, commits.get(b, '?')) for b in sorted(bugs_by_cap.get(r['id'], []))) or '—'
        miss = '; '.join('%s: %s' % (Ly, ', '.join(lay[Ly]['missing'])) for Ly in C.LAYERS if lay[Ly]['status'] != 'VERIFIED') or '—'
        L.append('| %s | %s | %s | **%s** | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (
            r['id'], r['name'], 'yes' if r['critical'] else 'no', st[r['status']], lay['component']['status'], lay['integration']['status'], lay['e2e']['status'],
            winst, dim('failure'), dim('recovery'), '; '.join(sorted(set(vu))) or '—', bl, miss))
    L += ['', '## Production files and tests per capability', '']
    for r in rows:
        L.append('### %s %s' % (r['id'], r['name']))
        L.append('- Production: `%s`' % r['code'])
        for Ly in C.LAYERS:
            ts = sorted(set(t for d in r['dims'].values() if not isinstance(d, C.NA) for t in d if C.layer_of(t, K) == Ly))
            L.append('- %s: %s' % (Ly, ', '.join('%s %s' % (t, {'Passed': 'PASS', 'Failed': 'FAIL', 'Skipped': 'NOT TESTED'}.get(C.resolve(t, res) if t.startswith('qa:') else res.get(t), 'NOT RUN')) for t in ts) or 'none'))
        L.append('- Regression: %s' % (', '.join(str(x) for x in (r.get('regression') or [])) or '—'))
        L.append('')
    open(os.path.join(here, 'MASTER-QA-LEDGER.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')

